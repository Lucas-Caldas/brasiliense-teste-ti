IF OBJECT_ID('TABELA_PAGAMENTOS_CONDOMINIO', 'U') IS NOT NULL DROP TABLE TABELA_PAGAMENTOS_CONDOMINIO;
IF OBJECT_ID('TABELA_APARTAMENTO', 'U') IS NOT NULL DROP TABLE TABELA_APARTAMENTO;
IF OBJECT_ID('TABELA_EDIFICIO', 'U') IS NOT NULL DROP TABLE TABELA_EDIFICIO;
IF OBJECT_ID('TABELA_CIDADE', 'U') IS NOT NULL DROP TABLE TABELA_CIDADE;
GO

CREATE TABLE TABELA_CIDADE (
    CODIGO_CIDADE INT NOT NULL PRIMARY KEY,
    NOME_CIDADE VARCHAR(50) NOT NULL,
    ESTADO CHAR(2) NOT NULL
);

CREATE TABLE TABELA_EDIFICIO (
    CODIGO_EDIFICIO INT NOT NULL PRIMARY KEY,
    NOME_EDIFICIO VARCHAR(50) NOT NULL,
    ANDARES INT NOT NULL,
    CODIGO_CIDADE INT NOT NULL,
    CONSTRAINT FK_EDIFICIO_CIDADE FOREIGN KEY (CODIGO_CIDADE) REFERENCES TABELA_CIDADE(CODIGO_CIDADE)
);

CREATE TABLE TABELA_APARTAMENTO (
    CODIGO_APARTAMENTO INT NOT NULL PRIMARY KEY,
    CODIGO_EDIFICIO INT NOT NULL,
    METRAGEM DECIMAL(18, 2) NOT NULL,
    ANDAR INT NOT NULL,
    NUMERO_QUARTOS INT NOT NULL,
    CONSTRAINT FK_APTO_EDIFICIO FOREIGN KEY (CODIGO_EDIFICIO) REFERENCES TABELA_EDIFICIO(CODIGO_EDIFICIO)
);

CREATE TABLE TABELA_PAGAMENTOS_CONDOMINIO (
    CODIGO_PAGAMENTO INT NOT NULL PRIMARY KEY,
    CODIGO_APARTAMENTO INT NOT NULL,
    DATA_PAGAMENTO DATETIME NOT NULL,
    VALOR_PAGAMENTO DECIMAL(18, 2) NOT NULL,
    CONSTRAINT FK_PAG_APTO FOREIGN KEY (CODIGO_APARTAMENTO) REFERENCES TABELA_APARTAMENTO(CODIGO_APARTAMENTO)
);
GO

-- Procedure corrigida (ver sql/sp_ranking_condominio_corrigida.sql)
CREATE OR ALTER PROCEDURE dbo.sp_ranking_condominio
    @dt_inicio  SMALLDATETIME,
    @dt_termino SMALLDATETIME
AS
BEGIN
    SET NOCOUNT ON;

    IF OBJECT_ID('tempdb.dbo.#tbl_cidades') IS NOT NULL
        DROP TABLE #tbl_cidades;

    SELECT
        C.CODIGO_CIDADE,
        C.NOME_CIDADE,
        C.ESTADO
    INTO #tbl_cidades
    FROM TABELA_CIDADE C;

    IF OBJECT_ID('tempdb.dbo.#tbl_edificios') IS NOT NULL
        DROP TABLE #tbl_edificios;

    SELECT
        E.CODIGO_EDIFICIO,
        E.NOME_EDIFICIO,
        E.ANDARES,
        E.CODIGO_CIDADE,
        C.NOME_CIDADE,
        C.ESTADO
    INTO #tbl_edificios
    FROM TABELA_EDIFICIO E
    INNER JOIN #tbl_cidades C ON (E.CODIGO_CIDADE = C.CODIGO_CIDADE);

    IF OBJECT_ID('tempdb.dbo.#tbl_apartamentos') IS NOT NULL
        DROP TABLE #tbl_apartamentos;

    SELECT
        A.CODIGO_APARTAMENTO,
        A.CODIGO_EDIFICIO,
        E.NOME_EDIFICIO,
        A.METRAGEM,
        A.ANDAR,
        A.NUMERO_QUARTOS,
        E.NOME_CIDADE,
        E.ESTADO
    INTO #tbl_apartamentos
    FROM TABELA_APARTAMENTO A
    INNER JOIN #tbl_edificios E ON (A.CODIGO_EDIFICIO = E.CODIGO_EDIFICIO);

    IF OBJECT_ID('tempdb.dbo.#tbl_pagamentos_condominios') IS NOT NULL
        DROP TABLE #tbl_pagamentos_condominios;

    SELECT
        C.CODIGO_APARTAMENTO,
        SUM(C.VALOR_PAGAMENTO) AS VALOR_PAGAMENTO
    INTO #tbl_pagamentos_condominios
    FROM TABELA_PAGAMENTOS_CONDOMINIO C
    WHERE C.DATA_PAGAMENTO BETWEEN @dt_inicio AND @dt_termino
    GROUP BY C.CODIGO_APARTAMENTO;

    SELECT TOP 3
        A.CODIGO_APARTAMENTO,
        A.CODIGO_EDIFICIO,
        A.NOME_EDIFICIO,
        A.METRAGEM,
        A.ANDAR,
        A.NUMERO_QUARTOS,
        A.NOME_CIDADE,
        A.ESTADO,
        PC.VALOR_PAGAMENTO
    FROM #tbl_pagamentos_condominios PC
    INNER JOIN #tbl_apartamentos A ON (PC.CODIGO_APARTAMENTO = A.CODIGO_APARTAMENTO)
    ORDER BY PC.VALOR_PAGAMENTO DESC;
END
GO
